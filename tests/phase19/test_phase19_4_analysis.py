def test_fp_fn_classification():
    with open("datasets/benchmark/results/v1.0.0/analysis/false_negatives.jsonl") as f:
        fns = [json.loads(line) for line in f]
        if fns:
            assert fns[0]["ground_truth"] == "malicious"
            assert fns[0]["is_malicious"] is False
            
    with open("datasets/benchmark/results/v1.0.0/analysis/false_positives.jsonl") as f:
        fps = [json.loads(line) for line in f]
        if fps:
            assert fps[0]["ground_truth"] == "benign"
            assert fps[0]["is_malicious"] is True
            
