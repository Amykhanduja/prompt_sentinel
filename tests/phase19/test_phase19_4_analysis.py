import json
import os
import pytest
from scripts.phase19_4_analysis import compute_metrics

def test_metric_semantics():
    # Test zero-support or benign-only metric edge cases
    # TP=0, FN=0, TN=10, FP=0 (Benign completely correct)
    m1 = compute_metrics(0, 10, 0, 0)
    assert m1["f1"] == 0.0 # Correctly bounded to 0
    assert m1["recall"] == 0.0
    assert m1["accuracy"] == 1.0
    
    # TP=10, FN=0, TN=0, FP=0 (Malicious completely correct)
    m2 = compute_metrics(10, 0, 0, 0)
    assert m2["f1"] == 1.0
    
def test_confidence_grouping():
    # Synthetic test to verify confidence bounds logic without mutating anything
    scores = [0.1, 0.45, 0.75, 0.95]
    vh = sum(1 for s in scores if s >= 0.8)
    h = sum(1 for s in scores if 0.6 <= s < 0.8)
    m = sum(1 for s in scores if 0.4 <= s < 0.6)
    l = sum(1 for s in scores if s < 0.4)
    assert vh == 1 and h == 1 and m == 1 and l == 1
    
